import { beforeEach, describe, expect, it, vi } from 'vitest'
import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react'
const native = vi.hoisted(() => ({ sync: vi.fn() }))
vi.mock('@/stores/settingsStore', () => ({ syncDesktopCredential: native.sync }))
import { DesktopApiKeyControl } from '@/features/settings/DesktopApiKeyControl'
beforeEach(() => { cleanup(); native.sync.mockReset(); native.sync.mockResolvedValue(true) })
describe('desktop key editing', () => {
  it('shows only a fixed mask, leaves focus unchanged and saves automatically after typing stops', async () => {
    render(<DesktopApiKeyControl kind="chat" configured label="对话 API Key" />)
    const input = screen.getByLabelText('对话 API Key')
    expect(input).toHaveValue('••••••••')
    expect(screen.queryByRole('button')).not.toBeInTheDocument()
    fireEvent.focus(input)
    fireEvent.blur(input)
    expect(native.sync).not.toHaveBeenCalled()
    fireEvent.focus(input)
    fireEvent.change(input, { target: { value: 'synthetic-new-key' } })
    await waitFor(() => expect(native.sync).toHaveBeenCalledWith('chat', { value: 'synthetic-new-key' }))
    expect(input).toHaveValue('synthetic-new-key')
    fireEvent.blur(input)
    await waitFor(() => expect(input).toHaveValue('••••••••'))
  })
  it('saves on blur and clears a configured key by explicit backspace', async () => {
    render(<DesktopApiKeyControl kind="chat" configured label="对话 API Key" />)
    const input = screen.getByLabelText('对话 API Key')
    fireEvent.focus(input)
    fireEvent.keyDown(input, { key: 'Backspace' })
    fireEvent.blur(input)
    await waitFor(() => expect(native.sync).toHaveBeenCalledWith('chat', { remove: true }))
  })
  it('retains the unsaved draft on failure and retries on blur without exposing error details', async () => {
    native.sync.mockRejectedValueOnce(new Error('synthetic-sensitive-detail'))
    render(<DesktopApiKeyControl kind="embedding" label="Embedding API Key" />)
    const input = screen.getByLabelText('Embedding API Key')
    fireEvent.change(input, { target: { value: 'synthetic-draft' } })
    fireEvent.blur(input)
    await screen.findByRole('alert')
    expect(screen.getByRole('alert')).not.toHaveTextContent('synthetic-sensitive-detail')
    expect(input).toHaveValue('synthetic-draft')
    fireEvent.blur(input)
    await waitFor(() => expect(input).toHaveValue(''))
  })
  it('does not let an older save clear newer input, and saves the new input while the first write is pending', async () => {
    let finish!: (saved: boolean) => void
    native.sync.mockImplementationOnce(() => new Promise<boolean>((resolve) => { finish = resolve }))
    render(<DesktopApiKeyControl kind="chat" label="对话 API Key" />)
    const input = screen.getByLabelText('对话 API Key')
    fireEvent.change(input, { target: { value: 'synthetic-first' } })
    fireEvent.blur(input)
    fireEvent.change(input, { target: { value: 'synthetic-second' } })
    await waitFor(() => expect(native.sync).toHaveBeenCalledWith('chat', { value: 'synthetic-second' }))
    finish(true)
    await waitFor(() => expect(input).toHaveValue(''))
    expect(native.sync).toHaveBeenCalledTimes(2)
  })
  it('cancels the unsaved timer when target identity changes', async () => {
    const view = render(<DesktopApiKeyControl key="target-a" kind="search" configured label="联网搜索 API Key" />)
    fireEvent.change(screen.getByLabelText('联网搜索 API Key'), { target: { value: 'synthetic-target-a' } })
    view.rerender(<DesktopApiKeyControl key="target-b" kind="search" label="联网搜索 API Key" />)
    expect(screen.getByLabelText('联网搜索 API Key')).toHaveValue('')
    await new Promise((resolve) => setTimeout(resolve, 550))
    expect(native.sync).not.toHaveBeenCalled()
  })
})
